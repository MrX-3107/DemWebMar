const COLOR_SWATCHES = {
  "Trắng kem": "white",
  "Hồng pastel": "pink",
  "Xanh dương": "blue",
  "Xanh lá": "green",
};

const COLOR_IMAGES = {
  "Trắng kem": "trang.jpg",
  "Hồng pastel": "hong.jpg",
  "Xanh dương": "xanhduong.jpg",
  "Xanh lá": "xanhla.jpg",
};

const requestedProductId =
  new URLSearchParams(window.location.search).get("id") || "1";
const product = Object.prototype.hasOwnProperty.call(
  PRODUCTS,
  requestedProductId,
)
  ? PRODUCTS[requestedProductId]
  : null;
const PRODUCT_ID = product ? requestedProductId : "1";
const notice = document.getElementById("notice");
let selectedColors = [];

function changeImage(image) {
  const mainImage = document.getElementById("mainImage");
  mainImage.src = image.src;
  mainImage.alt = image.alt;

  document.querySelectorAll(".thumb").forEach((thumb) => {
    thumb.classList.toggle("active", thumb === image);
  });
}

function selectColor(button) {
  const slot = Number(button.dataset.slot);
  const color = button.dataset.color;
  selectedColors[slot] = color;
  button
    .closest(".color-selection")
    .querySelectorAll(".color-option")
    .forEach((option) => option.classList.toggle("selected", option === button));

  const colorImage = COLOR_IMAGES[color];
  const colorThumb = Array.from(document.querySelectorAll(".thumb")).find(
    (thumb) => thumb.getAttribute("src") === colorImage,
  );
  if (colorThumb) changeImage(colorThumb);
  const currentProduct = product || PRODUCTS["1"];
  document.getElementById("productSku").textContent =
    slot === 0 && currentProduct.skuByColor
      ? currentProduct.skuByColor[color]
      : currentProduct.sku;
  notice.textContent = "Đã chọn màu: " + selectedColors.filter(Boolean).join(", ");
}

function changeQty(delta) {
  const input = document.getElementById("qty");
  input.value = Math.min(99, Math.max(1, (parseInt(input.value, 10) || 1) + delta));
}

function validateQty() {
  const input = document.getElementById("qty");
  input.value = Math.min(99, Math.max(1, parseInt(input.value, 10) || 1));
}

function updateEngraving() {
  const enabled = document.getElementById("engraving").checked;
  const nameInput = document.getElementById("engraveName");
  nameInput.hidden = !enabled;
  nameInput.required = enabled;
}

function renderProduct(item) {
  document.title = item.title + " | TT Bottly";
  document.getElementById("seoDescription").content = item.description;
  document.getElementById("productTitle").textContent = item.title;
  document.getElementById("breadcrumbProduct").textContent = item.title;
  document.getElementById("descriptionTitle").textContent = item.title;
  document.getElementById("descriptionText").textContent = item.description;
  document.getElementById("productLine").textContent = item.line;
  document.getElementById("productSku").textContent =
    item.sku || "Chưa cung cấp";
  document.getElementById("productCategory").textContent = item.category;
  document.getElementById("productCapacity").textContent = item.capacity;
  document.getElementById("productMaterial").textContent = item.material;
  document.getElementById("productColors").textContent =
    item.colors.join(", ") +
    (item.colorSlots > 1 ? ` (chọn ${item.colorSlots} màu)` : "");
  document.getElementById("productAccessory").textContent = item.accessory;
  document.getElementById("serviceLabel").textContent =
    item.serviceLabel || "Khắc tên theo yêu cầu";

  const featureList = document.getElementById("productFeatures");
  featureList.replaceChildren();
  item.features.forEach((feature) => {
    const listItem = document.createElement("li");
    listItem.textContent = feature;
    featureList.append(listItem);
  });

  selectedColors = Array.from(
    { length: item.colorSlots },
    (_, slot) =>
      slot === 0 && item.defaultColor
        ? item.defaultColor
        : item.colors[slot % item.colors.length],
  );
  const selectedImage = COLOR_IMAGES[selectedColors[0]];
  const gallery = document.querySelector(".thumbs");
  gallery.replaceChildren();
  const galleryImages = [...new Set([...item.images, ...Object.values(COLOR_IMAGES)])];
  galleryImages.forEach((src, index) => {
    const thumb = document.createElement("img");
    thumb.className = "thumb" + (src === selectedImage ? " active" : "");
    thumb.src = src;
    const colorName = Object.entries(COLOR_IMAGES).find(
      ([, colorSrc]) => colorSrc === src,
    )?.[0];
    thumb.alt = item.title + (colorName ? " - màu " + colorName : " - ảnh " + (index + 1));
    thumb.addEventListener("click", () => changeImage(thumb));
    gallery.append(thumb);
  });

  const mainImage = document.getElementById("mainImage");
  mainImage.src = selectedImage;
  mainImage.alt = item.title;

  const colorOptions = document.getElementById("colorOptions");
  colorOptions.replaceChildren();
  document.getElementById("productSku").textContent =
    (item.skuByColor && item.skuByColor[selectedColors[0]]) ||
    item.sku ||
    "Chưa cung cấp";
  for (let slot = 0; slot < item.colorSlots; slot += 1) {
    const selection = document.createElement("div");
    selection.className = "color-selection";
    const label = document.createElement("span");
    label.className = "color-selection__label";
    label.textContent =
      item.colorSlots > 1 ? `Màu bình ${slot + 1}` : "Chọn màu";
    selection.append(label);

    const options = document.createElement("div");
    options.className = "options";
    item.colors.forEach((color, index) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className =
        "color-option" +
        (color === selectedColors[slot] ? " selected" : "");
      button.dataset.color = color;
      button.dataset.slot = String(slot);

      const swatch = document.createElement("i");
      swatch.className = "swatch " + (COLOR_SWATCHES[color] || "white");
      swatch.setAttribute("aria-hidden", "true");
      button.append(swatch, document.createTextNode(color));
      button.addEventListener("click", () => selectColor(button));
      options.append(button);
    });
    selection.append(options);
    colorOptions.append(selection);
  }
}

function buyNow() {
  const quantity = Math.max(1, parseInt(document.getElementById("qty").value, 10) || 1);
  const chosenColors = selectedColors.filter(Boolean);
  const currentProduct = product || PRODUCTS["1"];
  const engraving = document.getElementById("engraving").checked;
  const engravingName = document.getElementById("engraveName").value.trim();
  if (chosenColors.length !== currentProduct.colorSlots) {
    notice.textContent = `Vui lòng chọn đủ ${currentProduct.colorSlots} màu cho sản phẩm.`;
    return;
  }

  const params = new URLSearchParams({
    productId: PRODUCT_ID,
    quantity: String(quantity),
    capacity: currentProduct.capacity.includes("700") ? "700ml" : "500ml",
    color: chosenColors.join(", "),
    engraving: String(engraving),
    engravingName: engravingName,
  });
  window.location.href = `order.html?${params.toString()}`;
}

if (!product) {
  notice.textContent =
    "Không tìm thấy sản phẩm này. Bạn đang xem sản phẩm đầu tiên.";
  renderProduct(PRODUCTS["1"]);
} else {
  renderProduct(product);
}

document
  .querySelector('.quantity button[aria-label="Giảm số lượng"]')
  .addEventListener("click", () => changeQty(-1));
document
  .querySelector('.quantity button[aria-label="Tăng số lượng"]')
  .addEventListener("click", () => changeQty(1));
document.getElementById("qty").addEventListener("change", validateQty);
document.getElementById("engraving").addEventListener("change", updateEngraving);
document.querySelector(".btn-buy").addEventListener("click", buyNow);
updateEngraving();
